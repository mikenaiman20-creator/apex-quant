"""Boundary calibration: the pass rate must rise with the planted IC.

The same generator and gate as the positive/negative tests are swept over
IC in {0.00, 0.05, 0.10, 0.15, 0.20} for 20 fixed seeds.  The pass-rate table is
written to ``artifacts/calibration_report.md`` and committed, so a future
regression that makes the gate accept noise (or reject a real edge) is visible.
"""
from __future__ import annotations

from datetime import date
from pathlib import Path

from backtest.metrics import deflated_sharpe_probability
from tests.calibration.synthetic import (
    BOUNDARY_ICS,
    BOUNDARY_SEEDS,
    TRADING_DAYS_PER_YEAR,
    build_seed,
    evaluate_gate,
)

REPORT_PATH = Path(__file__).resolve().parents[2] / "artifacts" / "calibration_report.md"


def _write_report(pass_rates, mean_pbo, mean_dsr, mean_net_sharpe):
    three_year = deflated_sharpe_probability(0.50, 3 * TRADING_DAYS_PER_YEAR, 1)
    fifteen_year = deflated_sharpe_probability(0.50, 15 * TRADING_DAYS_PER_YEAR, 1)
    lines = [
        "# Gate Calibration Report",
        "",
        f"Generated by `tests/calibration/test_boundary.py` on {date.today().isoformat()}.",
        "",
        "## Sample-size diagnosis",
        "",
        "The Phase 1 brief asked for 3 years of daily bars, a planted Sharpe of 0.50,",
        "and DSR >= 0.95.  Those three requirements are not jointly satisfiable:",
        "",
        f"- 3 years ({3 * TRADING_DAYS_PER_YEAR} observations) at Sharpe 0.50 "
        f"gives DSR {three_year['adjusted_sharpe']:.4f}.",
        f"- 15 years ({15 * TRADING_DAYS_PER_YEAR} observations) at Sharpe 0.50 "
        f"gives DSR {fifteen_year['adjusted_sharpe']:.4f}.",
        "- Approximately 2,773 observations (~11 years) are required for DSR 0.95 "
        "at Sharpe 0.50.",
        "",
        "The calibration therefore uses 15 years for margin.  The production",
        "thresholds (PBO < 0.20, DSR >= 0.95) are unchanged; only the synthetic",
        "sample length changed.  See `DECISIONS.md` (\"Gate Calibration Baseline\").",
        "",
        "## Panel and gate",
        "",
        "- 500 symbols, 15 years, daily observations.",
        "- Cross-sectional 5-day reversal, long/short quintiles, dollar-neutral.",
        "- Student-t(5) innovations, AR(1) autocorrelation 0.02.",
        "- Production `BTConfig` cost parameters (slippage 1 bp, half-spread 1 bp, "
        "half sell fee 0.15 bp per side).",
        "- Risk budget calibrated so the IC=0.15 portfolio has after-cost Sharpe 0.50.",
        "- Real `backtest.cpcv.evaluate_cpcv` gate, 6 CPCV groups, 1-day embargo, "
        "`n_trials=1` (Phase 2 owns the multi-trial penalty).",
        "",
        "## Boundary sweep",
        "",
        "| IC | Seeds | Pass rate | Mean PBO | Mean DSR | Mean net Sharpe |",
        "| --- | --- | --- | --- | --- | --- |",
    ]
    for index, information_coefficient in enumerate(BOUNDARY_ICS):
        lines.append(
            f"| {information_coefficient:.2f} | {len(BOUNDARY_SEEDS)} | "
            f"{pass_rates[index]:.2f} | {mean_pbo[index]:.3f} | "
            f"{mean_dsr[index]:.4f} | {mean_net_sharpe[index]:.3f} |"
        )
    lines.extend([
        "",
        "A pass requires PBO < 0.20 **and** DSR >= 0.95.  The pass rate is",
        "non-decreasing across the sweep and the mean DSR rises monotonically.",
        "",
    ])
    REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
    REPORT_PATH.write_text("\n".join(lines), encoding="utf-8")


def test_pass_rate_is_monotonic_in_planted_ic(monkeypatch):
    pass_counts = {information_coefficient: 0 for information_coefficient in BOUNDARY_ICS}
    pbo_totals = {information_coefficient: 0.0 for information_coefficient in BOUNDARY_ICS}
    dsr_totals = {information_coefficient: 0.0 for information_coefficient in BOUNDARY_ICS}
    sharpe_totals = {information_coefficient: 0.0 for information_coefficient in BOUNDARY_ICS}

    for seed in BOUNDARY_SEEDS:
        seed_panels = build_seed(seed, BOUNDARY_ICS)
        for information_coefficient in BOUNDARY_ICS:
            result = evaluate_gate(seed_panels, information_coefficient, monkeypatch)
            pass_counts[information_coefficient] += int(result.passed)
            pbo_totals[information_coefficient] += result.pbo
            dsr_totals[information_coefficient] += result.dsr_probability
            sharpe_totals[information_coefficient] += result.net_sharpe

    count = len(BOUNDARY_SEEDS)
    pass_rates = [pass_counts[information_coefficient] / count for information_coefficient in BOUNDARY_ICS]
    mean_pbo = [pbo_totals[information_coefficient] / count for information_coefficient in BOUNDARY_ICS]
    mean_dsr = [dsr_totals[information_coefficient] / count for information_coefficient in BOUNDARY_ICS]
    mean_sharpe = [sharpe_totals[information_coefficient] / count for information_coefficient in BOUNDARY_ICS]

    _write_report(pass_rates, mean_pbo, mean_dsr, mean_sharpe)

    assert REPORT_PATH.exists()
    report = REPORT_PATH.read_text(encoding="utf-8")
    assert "| IC | Seeds | Pass rate |" in report

    # A gate that rejects everything is as broken as one that accepts noise.
    assert pass_rates[0] == 0.0, pass_rates
    assert pass_rates[-1] > 0.0, pass_rates
    for left, right in zip(pass_rates, pass_rates[1:]):
        assert left <= right, pass_rates

    # The underlying statistic must move monotonically even where the pass rate
    # is pinned at 0 or 1.
    for left, right in zip(mean_dsr, mean_dsr[1:]):
        assert left < right, mean_dsr
